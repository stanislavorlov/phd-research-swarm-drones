"""
make_pairs.py -- build an offline dataset with TWO actions at every visited state.

    python3 make_pairs.py --n 300 --out data/pairs_train.pt
    python3 make_pairs.py --n 60 --start 200000 --out data/pairs_val.pt

Why: advantage weighting asks whether an action is better than what the data does at the SAME state.
A solver run once per scenario answers that question with "it is exactly what the data does", so A(s,a) = 0
for every row and offline RL provably reduces to behaviour cloning. Mixing quality levels does not fix it --
the trajectories diverge after t=0, so the two halves occupy different states and the quality difference is
absorbed into V(s). (Measured: adv gap between a weak1 half and a strong half is -0.026 with a decentralised
critic and +0.012 with a full-state one.)

This generates the missing ingredient. It rolls the STRONG trajectory, and at every state along it also solves
with a WEAK planner, storing both actions. Both branches are evaluated from the same state; only branch A is
committed, so the trajectory stays the strong one.

Cost: one weak receding-horizon solve per (scenario, step) -- 300 x 20 = 6,000 solves at 1x1x10, far cheaper
than one DAgger round at full settings (40,960 at 4x4x80).

Output keys: seeds, actions_a/channels_a (strong, from the stored plan), actions_b/channels_b (weak, solved
here), plus the two planners' settings. Observations, rewards and next states are regenerated by replay in
iql.pair_rows, following this project's seeds+plans convention.

NOTE: written without being executed by its author.
"""
from __future__ import annotations
import argparse, time
import numpy as np
import torch

from commenv import EnvConfig, CommEnv
from planner_state import plan_from_state


@torch.no_grad()
def build(seeds, cfg: EnvConfig, aA, cA, weak_kw, device="cpu", log=print):
    env = CommEnv(cfg, seeds)
    env.reset()
    S, N, T = env.B, cfg.n_agents, cfg.T
    aA = torch.as_tensor(aA).float()
    cA = torch.as_tensor(cA).long()
    aB = torch.zeros(S, T, N, 2)
    cB = torch.zeros(S, T, N, dtype=torch.long)
    t0 = time.time()
    for t in range(T):
        users_rem = env.users_traj[:, t + 1:cfg.T + 1]                 # [S, T-t, U, 2]
        p = plan_from_state(users_rem, env.uav, env.ch, cfg, device=device, rng_seed=t, **weak_kw)
        aB[:, t] = p["actions"][:, 0]
        cB[:, t] = p["channels"][:, 0]
        env.step(aA[:, t], cA[:, t])                                   # commit the strong branch only
        if t % 5 == 0 or t == T - 1:
            log(f"  step {t+1:2d}/{T}  weak solve {p['solve_s']:.1f}s  ({time.time()-t0:.0f}s total)")
    return aB.numpy(), cB.numpy()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--src", default="data/expert_train.pt", help="the STRONG dataset to branch from")
    ap.add_argument("--n", type=int, default=300, help="scenarios (keep modest: nobs is materialised)")
    ap.add_argument("--out", default="data/pairs_train.pt")
    ap.add_argument("--w_restarts", type=int, default=1)
    ap.add_argument("--w_rounds", type=int, default=1)
    ap.add_argument("--w_iters", type=int, default=10)
    ap.add_argument("--device", default="cuda" if torch.cuda.is_available() else "cpu")
    a = ap.parse_args()

    d = torch.load(a.src, map_location="cpu", weights_only=False)
    seeds = list(d["seeds"])[:a.n]
    aA = np.asarray(d["actions"])[:a.n]
    cA = np.asarray(d["channels"])[:a.n]
    cfg = EnvConfig(**d["cfg"]) if isinstance(d.get("cfg"), dict) else EnvConfig()
    weak_kw = dict(restarts=a.w_restarts, rounds=a.w_rounds, adam_iters=a.w_iters)
    print(f"branching {len(seeds)} scenarios from {a.src} (strong return "
          f"{float(np.mean(np.asarray(d['expert_return'])[:a.n])):.2f}); weak planner {weak_kw}")

    aB, cB = build(seeds, cfg, aA, cA, weak_kw, device=a.device)
    torch.save(dict(seeds=seeds, actions_a=aA, channels_a=cA, actions_b=aB, channels_b=cB,
                    strong_kw=dict(restarts=4, rounds=4, adam_iters=80), weak_kw=weak_kw,
                    cfg=cfg.__dict__), a.out)
    same = float((cB == cA).mean())
    moved = float(np.linalg.norm(aB - aA, axis=-1).mean())
    print(f"saved {a.out}\n  channel agreement A vs B: {same:.3f}   mean |a_A - a_B|: {moved:.3f}")
    print("  If agreement is ~1.0 and the displacement gap ~0, the weak planner reproduces the strong one\n"
          "  and there is still no action diversity -- lower the weak budget further before training.")


if __name__ == "__main__":
    main()